import gzip

import pytest

from app.services.website_intel.crawl.blocks import BlockClassifier
from app.services.website_intel.models import PageVerdict

HTML = "text/html; charset=utf-8"


@pytest.fixture(scope="module")
def classifier() -> BlockClassifier:
    return BlockClassifier()


def _read(fixture_path, name: str) -> str:
    return fixture_path(name).read_text(encoding="utf-8")


def test_azure_application_gateway_403(classifier, fixture_path) -> None:
    body = _read(fixture_path, "crawl_block_azure_403.html")
    assert (
        classifier.classify(status_code=403, headers={}, body=body, content_type="text/html")
        is PageVerdict.waf_block
    )


def test_reader_proxy_200_with_azure_challenge_is_blocked(classifier, fixture_path) -> None:
    body = _read(fixture_path, "crawl_block_jina_azure_waf.json")
    verdict = classifier.classify(status_code=200, headers={}, body=body, content_type="application/json")
    assert verdict is PageVerdict.waf_block
    assert verdict.is_block


def test_cloudflare_challenge_by_header_and_body(classifier, fixture_path) -> None:
    assert (
        classifier.classify(status_code=403, headers={"CF-Mitigated": "challenge"}, body="")
        is PageVerdict.cf_challenge
    )
    body = _read(fixture_path, "crawl_block_cloudflare_challenge.html")
    assert (
        classifier.classify(status_code=503, headers={}, body=body, content_type=HTML)
        is PageVerdict.cf_challenge
    )
    assert (
        classifier.classify(status_code=200, headers={}, body=body, content_type=HTML)
        is PageVerdict.cf_challenge
    )


def test_akamai_aws_imperva_sucuri(classifier, fixture_path) -> None:
    akamai = _read(fixture_path, "crawl_block_akamai.html")
    assert (
        classifier.classify(status_code=403, headers={"Server": "AkamaiGHost"}, body=akamai)
        is PageVerdict.waf_block
    )
    assert (
        classifier.classify(status_code=403, headers={}, body=akamai, content_type=HTML)
        is PageVerdict.waf_block
    )
    aws = "<html><body><h1>403 ERROR</h1>Request blocked. Generated by cloudfront (CloudFront)</body></html>"
    assert classifier.classify(status_code=403, headers={}, body=aws) is PageVerdict.waf_block
    imperva = '<html><head><META NAME="robots"></head><iframe src="/_Incapsula_Resource?x=1"></iframe></html>'
    assert (
        classifier.classify(status_code=200, headers={}, body=imperva, content_type=HTML)
        is PageVerdict.waf_block
    )
    assert (
        classifier.classify(status_code=403, headers={"X-Sucuri-ID": "1"}, body="denied")
        is PageVerdict.waf_block
    )


@pytest.mark.parametrize(
    ("status", "body", "expected"),
    [
        (429, "", PageVerdict.rate_limited),
        (401, "", PageVerdict.login_wall),
        (451, "", PageVerdict.geo_block),
        (
            403,
            "<html><body>This content is not available in your region.</body></html>",
            PageVerdict.geo_block,
        ),
        (404, "", PageVerdict.not_found),
        (410, "", PageVerdict.gone),
        (500, "", PageVerdict.server_error),
        (502, "", PageVerdict.server_error),
        (403, "<html><body>Forbidden</body></html>", PageVerdict.error),
        (304, "", PageVerdict.not_modified),
    ],
)
def test_status_rows(classifier, status: int, body: str, expected: PageVerdict) -> None:
    assert classifier.classify(status_code=status, headers={}, body=body, content_type=HTML) is expected


def test_network_error(classifier) -> None:
    assert (
        classifier.classify(status_code=None, headers={}, body=None, network_error=True) is PageVerdict.error
    )


@pytest.mark.parametrize(
    ("name", "expected"),
    [
        ("crawl_block_login_wall.html", PageVerdict.login_wall),
        ("crawl_block_soft_404.html", PageVerdict.soft_404),
        ("crawl_block_consent_wall.html", PageVerdict.consent_wall),
        ("crawl_block_js_shell.html", PageVerdict.js_shell),
    ],
)
def test_success_status_rows(classifier, fixture_path, name: str, expected: PageVerdict) -> None:
    body = _read(fixture_path, name)
    assert classifier.classify(status_code=200, headers={}, body=body, content_type=HTML) is expected


def test_script_heavy_shell_and_real_pages(classifier, fixture_path) -> None:
    shell = "<html><body><div id='app'></div><script>" + "x" * 5000 + "</script></body></html>"
    assert (
        classifier.classify(status_code=200, headers={}, body=shell, content_type=HTML)
        is PageVerdict.js_shell
    )
    article = (
        "<html><body><main>" + "<p>We offer dental implants and cleanings.</p>" * 40 + "</main></body></html>"
    )
    assert classifier.classify(status_code=200, headers={}, body=article, content_type=HTML) is PageVerdict.ok
    pdf = classifier.classify(status_code=200, headers={}, body="%PDF-1.7", content_type="application/pdf")
    assert pdf is PageVerdict.ok


def test_apollo_homepage_is_ok(classifier, fixture_path) -> None:
    path = fixture_path("extract_apollo_home.html.gz")
    if not path.exists():
        pytest.skip("apollo homepage fixture not present")
    body = gzip.decompress(path.read_bytes()).decode("utf-8", errors="replace")
    assert classifier.classify(status_code=200, headers={}, body=body, content_type=HTML) is PageVerdict.ok


def test_article_mentioning_waf_is_not_blocked(classifier) -> None:
    text = "<p>Azure WAF protects web apps from bots. Checking you're not a robot is common.</p>" * 40
    body = f"<html><body><article>{text}</article></body></html>"
    assert classifier.classify(status_code=200, headers={}, body=body, content_type=HTML) is PageVerdict.ok
