def valid_country(code: str | None) -> str | None:
    if not code:
        return None
    upper = code.strip().upper()
    return upper if upper in ISO_COUNTRIES else None


def geo_ref(city: str | None, region: str | None, country: str | None) -> GeoRef | None:
    country_code = valid_country(country)
    if country_code is None:
        return None
    return GeoRef(city=(city or None), region=(region or None), country_iso2=country_code)
