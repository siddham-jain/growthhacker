from app.evaluation.policy.coverage import CHECKED_MODELS, SCORER_KEYED_FIELDS
from app.evaluation.policy.registry import (
    CELL_TEXT,
    GUARDRAIL_TEXT,
    GUARDRAILS,
    FeatureRegistry,
    FeatureSpec,
)
from app.evaluation.reporting.markdown import table

SOURCE_LABELS = {
    "yt_data_public": "YT public",
    "yt_analytics_oauth": "YT Analytics (OAuth)",
    "website": "website",
    "web_search": "web search",
    "client_input": "client input",
    "spotlit_ai_tracking": "Spotlit AI tracking",
    "llm": "LLM",
    "internal": "internal",
}


def _source_maths(spec: FeatureSpec) -> str:
    sources = " + ".join(SOURCE_LABELS[s] for s in spec.sources)
    maths = ", ".join(m.replace("_", " ") for m in spec.maths)
    return f"{sources} · {maths}"


def _cell(value: str) -> str:
    return f"**{value}**" if value == "FLAG" else value


def render_policy_matrix(registry: FeatureRegistry) -> str:
    specs = registry.all()
    flagged = registry.flagged()
    flag_cells = sum(len(spec.flagged_guardrails) for spec in flagged)
    lines = [
        "# Feature-policy matrix",
        "",
        "Generated by `python -m app.evaluation policy render` from the `FeatureSpec` registry "
        "(`app/evaluation/policy/features.py`). Do not edit by hand; CI fails when this file and the "
        "registry disagree.",
        "",
        "Every displayed figure is YouTube API data plus simple maths, labelled 'calculated by GrowthHacker, "
        "not a YouTube metric'. Statistical gates are internal filters. There is no composite channel score "
        "and no channel ranking. Storing API data past 30 days needs an accepted Section L audit.",
        "",
        "## Guardrails",
        "",
        *(f"- **{g}** {GUARDRAIL_TEXT[g]}" for g in GUARDRAILS),
        "",
        "Cells: " + "; ".join(f"**{cell}** {text}" for cell, text in CELL_TEXT.items()) + ".",
        "",
        f"## Matrix ({len(specs)} features, {flag_cells} FLAG cells on {len(flagged)} features)",
        "",
        table(
            ["#", "Feature (owner)", "Source · maths", *GUARDRAILS, "Condition / mitigation"],
            [
                [
                    spec.number,
                    f"{spec.name} ({spec.owner})",
                    _source_maths(spec),
                    *(_cell(spec.checks[g]) for g in GUARDRAILS),
                    spec.condition,
                ]
                for spec in specs
            ],
        ),
        "",
        "## Needs reviewer sign-off (FLAG)",
        "",
        *(
            f"- **#{spec.number} {spec.name}** ({', '.join(spec.flagged_guardrails)}): {spec.review_note}"
            for spec in flagged
        ),
        "",
        "## Coverage",
        "",
        "CI checks that every field of these objects is covered by a row:",
        "",
        *(f"- `{model.__module__}.{model.__name__}`" for model in CHECKED_MODELS),
        *(
            f"- `ScoreBreakdown.{field}` keys: {', '.join(f'`{key}`' for key in sorted(keyed))}"
            for field, keyed in SCORER_KEYED_FIELDS.items()
        ),
    ]
    return "\n".join(lines) + "\n"
